"""Baseline Direct-Execution IDS Agent (`ids_baseline.py`).

Implements the Baseline Scenario (Static IDS without Model Context Protocol):
1. Pulls raw Open vSwitch telemetry logs via `OVSAdapter.get_telemetry_stream()`.
2. Embeds the raw logs together with an Open vSwitch (`ovs-ofctl`) documentation
   reference snippet directly into the LLM prompt.
3. Receives a raw CLI mitigation command string generated by the LLM.
4. Passes the generated command string directly to `OVSAdapter.apply_mitigation()`.
5. Records high-precision latency, signaling byte overhead, token usage, and
   `psutil` CPU/RAM footprint into `metrics_results.csv`.
"""

from __future__ import annotations

import argparse
import logging
import os
import time
from typing import Any

from llm_client import BaseLLMClient, LLMClientFactory, LLMResponse
from metrics_collector import EdgeResourceMonitor, IncidentMetrics, MetricsLogger
from network_adapter import MitigationResult, NetworkAdapter, OVSAdapter, load_dotenv

load_dotenv()

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] [BASELINE-IDS] %(message)s",
)
logger = logging.getLogger(__name__)

OVS_DOCUMENTATION_SNIPPET: str = """
=== OPEN VSWITCH (ovs-ofctl) OFFICIAL COMMAND REFERENCE SNIPPET ===
Synopsis:
  ovs-ofctl add-flow <switch> <flow>

Flow Syntax & Match Fields:
  priority=<0-65535>     Rule evaluation precedence (higher overrides lower).
  dl_type=0x0800         Match IPv4 packets (required before nw_src/nw_dst).
  nw_proto=<6|17|1>      Match TCP (6), UDP (17), or ICMP (1).
  nw_src=<ip>[/<mask>]   Match source IPv4 address or CIDR subnet.
  nw_dst=<ip>[/<mask>]   Match destination IPv4 address or CIDR subnet.
  tp_src=<port>          Match transport-layer source port.
  tp_dst=<port>          Match transport-layer destination port.
  actions=drop           Drop matching packets at the data-plane switch.
  actions=normal         Forward packets via standard L2/L3 pipeline.

Example Mitigation Command (Drop malicious source IPv4 traffic on bridge br0):
  ovs-ofctl add-flow br0 "priority=500,dl_type=0x0800,nw_src=10.200.0.20,actions=drop"
===================================================================
""".strip()

BASELINE_SYSTEM_INSTRUCTION: str = (
    "You are an autonomous 6G Multi-Access Edge Computing (MEC) Intrusion Detection "
    "and Prevention System (IDS/IPS) operating directly on an Open vSwitch (OVS) "
    "User Plane Function (UPF) node. Analyze the raw OpenFlow telemetry logs, "
    "identify the most anomalous/attacking source IPv4 address (ignoring protected "
    "gateway 10.200.0.1 and switch 10.200.0.10), and output ONLY a single raw "
    "`ovs-ofctl add-flow` command string to drop packets from that source IP. "
    "Do not include explanations or markdown formatting."
)


class BaselineIDSAgent:
    """Direct-execution IDS agent that couples raw logs to LLM-generated CLI strings."""

    def __init__(
        self,
        adapter: NetworkAdapter | None = None,
        llm_client: BaseLLMClient | None = None,
        metrics_logger: MetricsLogger | None = None,
        max_log_lines: int = 50,
    ) -> None:
        """Initialize the Baseline IDS Agent.

        Args:
            adapter: Data-plane network adapter (defaults to `OVSAdapter`).
            llm_client: Universal LLM client (defaults to `LLMClientFactory.create_client()`).
            metrics_logger: CSV metrics logger writing to `metrics_results.csv`.
            max_log_lines: Number of raw log lines pulled per inspection cycle.
        """
        self.adapter: NetworkAdapter = adapter or OVSAdapter()
        self.llm_client: BaseLLMClient = llm_client or LLMClientFactory.create_client()
        self.metrics_logger: MetricsLogger = metrics_logger or MetricsLogger()
        self.max_log_lines: int = max_log_lines

    def build_prompt(self, raw_telemetry: str) -> str:
        """Construct the full prompt combining OVS documentation and raw logs."""
        bridge_name = getattr(self.adapter, "bridge_name", os.getenv("OVS_BRIDGE", "br0"))
        return (
            f"{OVS_DOCUMENTATION_SNIPPET}\n\n"
            f"Target OVS Bridge: {bridge_name}\n"
            f"Protected IPs (DO NOT BLOCK): 127.0.0.1, 10.200.0.1, 10.200.0.10\n\n"
            f"=== RAW OPENFLOW TELEMETRY STREAM ===\n"
            f"{raw_telemetry}\n"
            f"=====================================\n\n"
            f"Output ONLY the exact `ovs-ofctl add-flow {bridge_name} ...` mitigation command "
            f"to drop traffic from the attacking source IP (or `NONE` if no anomaly exists):"
        )

    def run_single_iteration(self) -> IncidentMetrics:
        """Execute one full detection-and-mitigation cycle and log metrics to CSV.

        Returns:
            The recorded `IncidentMetrics` for this cycle.
        """
        with EdgeResourceMonitor() as resource_monitor:
            cycle_start_ns = time.perf_counter()

            # Step 1: Pull raw telemetry logs through the NetworkAdapter
            raw_logs = self.adapter.get_telemetry_stream(max_lines=self.max_log_lines)
            telemetry_bytes = len(raw_logs.encode("utf-8"))

            # Step 2: Build prompt with OVS documentation snippet + raw logs
            user_prompt = self.build_prompt(raw_logs)

            # Step 3: Query LLM (Host B over SSH tunnel or Gemini)
            llm_response: LLMResponse = self.llm_client.generate(
                prompt=user_prompt,
                system_instruction=BASELINE_SYSTEM_INSTRUCTION,
            )

            generated_cmd = llm_response.text.strip()
            logger.info(
                "LLM inference completed in %.2f ms (prompt_tokens=%d, completion_tokens=%d): %s",
                llm_response.inference_latency_ms,
                llm_response.prompt_tokens,
                llm_response.completion_tokens,
                generated_cmd,
            )

            # Step 4: Execute raw generated mitigation string via Adapter
            if generated_cmd.upper() == "NONE" or not generated_cmd:
                mitigation_result = MitigationResult(
                    success=True,
                    command_executed="NONE",
                    stdout="No anomaly detected by LLM.",
                    stderr="",
                    execution_time_ms=0.0,
                    simulated=True,
                )
            else:
                mitigation_result = self.adapter.apply_mitigation(generated_cmd)

            deployment_delay_ms = (time.perf_counter() - cycle_start_ns) * 1000.0

        # Control-plane signaling overhead includes LLM HTTP request+response envelopes
        # plus the adapter command dispatch payload
        adapter_cmd_bytes = len(mitigation_result.command_executed.encode("utf-8"))
        signaling_overhead_bytes = llm_response.signaling_bytes + adapter_cmd_bytes

        metrics = IncidentMetrics(
            timestamp_utc=MetricsLogger.utc_now_iso(),
            scenario="baseline_direct",
            provider=llm_response.provider,
            model=llm_response.model,
            deployment_delay_ms=round(deployment_delay_ms, 4),
            inference_latency_ms=round(llm_response.inference_latency_ms, 4),
            adapter_execution_ms=round(mitigation_result.execution_time_ms, 4),
            signaling_overhead_bytes=signaling_overhead_bytes,
            telemetry_payload_bytes=telemetry_bytes,
            prompt_tokens=llm_response.prompt_tokens,
            completion_tokens=llm_response.completion_tokens,
            total_tokens=llm_response.total_tokens,
            cpu_peak_percent=resource_monitor.cpu_peak_percent,
            ram_peak_mb=resource_monitor.ram_peak_mb,
            mitigation_success=mitigation_result.success,
            mitigation_command=mitigation_result.command_executed,
        )

        self.metrics_logger.log_incident(metrics)
        logger.info(
            "Cycle finished | Deployment Delay: %.2f ms | Signaling: %d B | "
            "Tokens: %d | CPU Peak: %.1f%% | RAM Peak: %.2f MB | Success: %s",
            metrics.deployment_delay_ms,
            metrics.signaling_overhead_bytes,
            metrics.total_tokens,
            metrics.cpu_peak_percent,
            metrics.ram_peak_mb,
            metrics.mitigation_success,
        )
        return metrics


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments for the Baseline IDS experiment runner."""
    parser = argparse.ArgumentParser(
        description="Baseline Direct-Execution IDS Agent (without MCP)"
    )
    parser.add_argument(
        "--iterations",
        type=int,
        default=1,
        help="Number of detection/mitigation iterations to run (0 for infinite loop).",
    )
    parser.add_argument(
        "--interval",
        type=float,
        default=float(os.getenv("POLL_INTERVAL_SECONDS", "5.0")),
        help="Wait interval in seconds between iterations.",
    )
    parser.add_argument(
        "--max-lines",
        type=int,
        default=int(os.getenv("TELEMETRY_TAIL_LINES", "50")),
        help="Number of raw OVS telemetry lines to inspect per iteration.",
    )
    parser.add_argument(
        "--provider",
        type=str,
        default=None,
        help="Override LLM provider ('ollama' or 'gemini').",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Enable OVS adapter dry-run mode (do not invoke system ovs-ofctl).",
    )
    return parser.parse_args()


def main() -> None:
    """Entry point for executing the Baseline IDS evaluation."""
    args = parse_args()
    adapter = OVSAdapter(dry_run=True if args.dry_run else None)
    llm_client = LLMClientFactory.create_client(provider=args.provider)
    agent = BaselineIDSAgent(
        adapter=adapter,
        llm_client=llm_client,
        max_log_lines=args.max_lines,
    )

    iteration = 0
    try:
        while args.iterations == 0 or iteration < args.iterations:
            iteration += 1
            logger.info("--- Starting Baseline IDS Iteration %d ---", iteration)
            try:
                agent.run_single_iteration()
            except Exception as exc:
                logger.error("Baseline IDS iteration %d failed: %s", iteration, exc)
            if args.iterations == 0 or iteration < args.iterations:
                time.sleep(args.interval)
    except KeyboardInterrupt:
        logger.info("Baseline IDS stopped by user.")


if __name__ == "__main__":
    main()
